// Copies the prepared GeoJSON from ../upu-precko-zapad-map-data into public/data
// and makes sure data/ownership.json exists (the ownership file kept in the repo).
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const app = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.resolve(app, '..', 'upu-precko-zapad-map-data');
const dst = path.join(app, 'public', 'data');

await fs.mkdir(dst, { recursive: true });
for (const f of ['plots.geojson', 'zones.geojson', 'boundary.geojson', 'review.json', 'roads.geojson', 'road_lines.geojson', 'road_labels.geojson']) {
  await fs.copyFile(path.join(src, f), path.join(dst, f));
}

const own = path.join(app, 'data', 'ownership.json');
try {
  await fs.access(own);
} catch {
  await fs.mkdir(path.dirname(own), { recursive: true });
  await fs.writeFile(own, JSON.stringify({ version: 1, savedAt: null, plots: {}, reviews: {} }, null, 2) + '\n');
}
// read-only seed for static builds without the local file API
await fs.copyFile(own, path.join(dst, 'ownership.seed.json'));

// The parcel ids /api/oss-parcel may be asked about: exactly the parcels on the map.
// The file is committed as well, so the function also builds where this script has not run;
// a unit test fails if it no longer matches plots.geojson.
const plots = JSON.parse(await fs.readFile(path.join(src, 'plots.geojson'), 'utf8'));
const ids = plots.features.map((f) => f.properties.oss_parcel_id).filter(Number.isInteger).sort((a, b) => a - b);
const lines = [];
for (let i = 0; i < ids.length; i += 10) lines.push('  ' + ids.slice(i, i + 10).join(', ') + ',');
const allowlist =
  '// Generated by scripts/sync-data.mjs from plots.geojson (oss_parcel_id of every plot) - do not edit.\n' +
  `export const OSS_PARCEL_IDS: readonly number[] = [\n${lines.join('\n')}\n];\n`;
const allowFile = path.join(app, 'server', 'parcelAllowlist.generated.ts');
const before = await fs.readFile(allowFile, 'utf8').catch(() => '');
if (before.replace(/\r\n/g, '\n') !== allowlist) {
  await fs.mkdir(path.dirname(allowFile), { recursive: true });
  await fs.writeFile(allowFile, allowlist);
}
console.log('data synced to public/data');
